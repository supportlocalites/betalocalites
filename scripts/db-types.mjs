// Regenerates src/db/generated/schema.ts from a database that has every migration
// applied. The SQL migrations stay the only source of truth for the structure.
//
// Usage: DATABASE_ADMIN_URL=postgres://... npm run db:types
import { execFileSync } from 'node:child_process';
import { readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src', 'db', 'generated');

execFileSync('npx', ['drizzle-kit', 'pull'], { cwd: root, stdio: 'inherit' });

// drizzle-kit also writes a migration and metadata; ours live in db/migrations.
for (const f of await readdir(out)) {
  if (f.endsWith('.sql') || f === 'meta') await rm(path.join(out, f), { recursive: true });
}

const file = path.join(out, 'schema.ts');
let src = await readFile(file, 'utf8');
const map = { citext: 'citext', geography: 'geography', tsvector: 'tsvector' };
src = src.replace(
  /\t\/\/ TODO: failed to parse database type '(\w+)'\n(\t\w+: )unknown\(/g,
  (whole, type, lead) => {
    if (!map[type]) throw new Error(`Unknown database type ${type}: add it to src/db/custom-types.ts`);
    return `${lead}${map[type]}(`;
  },
);
if (src.includes('unknown(')) throw new Error('A database type is still unknown; see src/db/generated/schema.ts');
src = `// GENERATED by scripts/db-types.mjs from the database. Do not edit by hand.\nimport { citext, geography, tsvector } from '../custom-types';\n${src}`;
await writeFile(file, src);
console.log('src/db/generated/schema.ts updated.');
