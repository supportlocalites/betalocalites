const SCENE = { parties: 'parties', wellness: 'wellness', spiritual: 'spiritual', beauty: 'beauty', kids: 'kids', home: 'home' };

const initialsOf = (name) =>
  name
    .replace(/&/g, ' & ')
    .split(/\s+/)
    .filter((w) => /^[A-Z&]/.test(w) && !['The', 'Co.'].includes(w))
    .map((w) => w[0])
    .join('')
    .slice(0, 3);

