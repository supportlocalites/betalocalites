-- =============================================================================
-- Localites — migration 0001: Stage 1 foundation
-- =============================================================================
-- Approved: architecture D-00, Stage 1 D-23 (10 October 2026). Built from the
-- reviewed proposal in docs/schema/stage1-proposed.sql, with the later decisions:
--   * activity tracking (D-22, ADR-023): activity_event + vendor_daily_stats
--     replace analytics_event;
--   * Suggest a business (D-25, ADR-027): vendor_suggestion;
--   * saved_vendor moves to Stage 2 (consumer accounts arrive then);
--   * the restricted app_server role and its policies (ADR-004) are created here.
-- Never edit this file once it has been applied anywhere; add a new migration.
--
-- Conventions (see docs/B-domain-and-data-model.md §1):
--   * Primary keys are UUIDs, generated by the application as UUID v7.
--     gen_random_uuid() defaults exist only as a safety net.
--   * Statuses are text + CHECK constraints, not Postgres enums: adding a value
--     is a one-line, non-locking migration.
--   * Money is integer cents + ISO currency code.
--   * Timestamps are timestamptz (stored UTC).
--   * Nothing important is hard-deleted; relationships end with a timestamp.
--   * Extensions live in their own schema, "extensions" (Supabase's layout);
--     the search path below includes it.
-- =============================================================================

create schema if not exists extensions;
create extension if not exists citext with schema extensions;
create extension if not exists pg_trgm with schema extensions;
create extension if not exists postgis with schema extensions;
set search_path = public, extensions;

