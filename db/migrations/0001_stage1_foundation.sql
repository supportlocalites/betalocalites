create function enforce_attribute_value_type() returns trigger
language plpgsql as $$
declare
  def attribute_definition%rowtype;
begin
  select * into strict def from attribute_definition where id = new.attribute_definition_id;

  if def.data_type = 'boolean' and new.value_boolean is null then
    raise exception 'attribute "%" expects a yes/no value', def.key;
  elsif def.data_type = 'number' and new.value_number is null then
    raise exception 'attribute "%" expects a number', def.key;
  elsif def.data_type = 'text' and new.value_text is null then
    raise exception 'attribute "%" expects text', def.key;
  elsif def.data_type in ('single_choice', 'multi_choice') then
    if new.option_id is null then
      raise exception 'attribute "%" expects one of its listed options', def.key;
    end if;
    if not exists (select 1 from attribute_option o
                   where o.id = new.option_id and o.attribute_definition_id = def.id) then
      raise exception 'that option does not belong to attribute "%"', def.key;
    end if;
    if def.data_type = 'single_choice' and exists (
         select 1 from vendor_attribute_value v
         where v.vendor_id = new.vendor_id
           and v.attribute_definition_id = def.id
           and v.id <> new.id) then
      raise exception 'attribute "%" allows only one choice', def.key;
    end if;
  end if;
  return new;
end $$;

-- Known limitation: the single_choice check above can be raced by two concurrent
-- inserts for the same vendor+attribute. Acceptable for Stage 1 (listings are edited
-- by one person at a time); the application also serialises attribute saves per
-- vendor. Revisit if bulk import is introduced.
create trigger vendor_attribute_value_type
  before insert or update on vendor_attribute_value
  for each row execute function enforce_attribute_value_type();

-- Tier 3 guard: a key that is a managed attribute can't hide in profile_extras.
create function enforce_profile_extras_keys() returns trigger
language plpgsql as $$
declare
  clash text;
begin
  select d.key into clash
  from attribute_definition d
  where d.key in (select jsonb_object_keys(new.profile_extras))
  limit 1;
  if clash is not null then
    raise exception '"%" is a managed attribute; store it as an attribute value, not in profile_extras', clash;
  end if;
  return new;
end $$;

create trigger vendor_profile_extras_guard
  before insert or update of profile_extras on vendor
  for each row execute function enforce_profile_extras_keys();

