-- =============================================================================
-- ACCESS CONTROL  (second lock — ADR-004)
-- =============================================================================
-- Row-level security is on, and forced, for every table. There are NO policies for
-- Supabase's browser-facing roles (anon, authenticated): they can read nothing.
-- The application connects as the restricted role app_server, which can read and
-- write data but cannot change the structure or edit audit history. Its login and
-- password are set outside git (see docs/F-operational-runbook.md).

do $$
declare t text;
begin
  if not exists (select 1 from pg_roles where rolname = 'app_server') then
    create role app_server nologin;
  end if;

  foreach t in array array[
    'app_user', 'platform_role', 'municipality', 'category', 'attribute_definition',
    'attribute_option', 'attribute_definition_category', 'media_asset', 'vendor',
    'vendor_slug_history', 'vendor_link', 'vendor_member', 'vendor_category',
    'vendor_service', 'vendor_service_area', 'vendor_attribute_value', 'vendor_media',
    'vendor_claim', 'verification_record', 'collection', 'collection_item',
    'vendor_suggestion', 'status_change', 'audit_log', 'activity_event', 'vendor_daily_stats'
  ] loop
    execute format('alter table %I enable row level security', t);
    execute format('alter table %I force row level security', t);
    execute format('create policy app_server_all on %I to app_server using (true) with check (true)', t);
  end loop;

  -- Belt and braces on Supabase: take away the default table grants from the
  -- browser-facing roles as well.
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on all tables in schema public from anon;
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    revoke all on all tables in schema public from authenticated;
  end if;
end $$;

alter role app_server set search_path = public, extensions;
grant usage on schema public, extensions to app_server;
grant select, insert, update on all tables in schema public to app_server;
revoke update, delete on status_change, audit_log from app_server;
grant usage, select on all sequences in schema public to app_server;
