-- Tier 2 metadata: the registry of filterable, typed vendor attributes.
create table attribute_definition (
  id             uuid primary key default gen_random_uuid(),
  key            text not null unique check (key ~ '^[a-z][a-z0-9_]{1,62}$'),
  label          text not null,
  help_text      text,
  data_type      text not null
                 check (data_type in ('boolean', 'number', 'single_choice', 'multi_choice', 'text')),
  unit           text,                              -- e.g. 'guests', 'km'
  is_filterable  boolean not null default false,
  is_public      boolean not null default true,
  is_active      boolean not null default true,
  sort_order     int not null default 0,
  -- Free text is never a filter: it can't be filtered consistently.
  check (not (data_type = 'text' and is_filterable))
);

create table attribute_option (
  id                       uuid primary key default gen_random_uuid(),
  attribute_definition_id  uuid not null references attribute_definition(id),
  value                    text not null check (value ~ '^[a-z0-9_]+$'),
  label                    text not null,
  sort_order               int not null default 0,
  is_active                boolean not null default true,
  unique (attribute_definition_id, value)
);

