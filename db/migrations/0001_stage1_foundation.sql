create table vendor (
  id                       uuid primary key default gen_random_uuid(),
  slug                     slug_text not null unique,
  display_name             text not null check (char_length(display_name) between 1 and 160),
  tagline                  text check (char_length(tagline) <= 160),
  description              text check (char_length(description) <= 5000),
  primary_municipality_id  uuid not null references municipality(id),

  -- Contact the vendor has published or provided (D-03, D-04). Messaging on
  -- Localites arrives in Stage 2, for claimed and verified listings (D-04, D-05).
  website_url              text check (website_url ~ '^https?://'),
  public_email             citext,
  public_phone             text check (public_phone ~ '^\+?[0-9 ().-]{7,20}$'),

  -- Lifecycle (transitions enforced in application code, ADR-017).
  listing_status           text not null default 'draft'
                           check (listing_status in ('draft', 'pending_review', 'published', 'unpublished', 'archived')),
  claim_status             text not null default 'unclaimed'
                           check (claim_status in ('unclaimed', 'claim_pending', 'claimed')),
  verification_status      text not null default 'unverified'
                           check (verification_status in ('unverified', 'verified', 'lapsed')),
  verified_at              timestamptz,
  source                   text not null check (source in ('admin_entered', 'vendor_submitted')),

  -- Tier 3: display-only extras. Never filtered on. Guarded by trigger below.
  profile_extras           jsonb not null default '{}'::jsonb
                           check (jsonb_typeof(profile_extras) = 'object'),

  search_document          tsvector generated always as (
                             setweight(to_tsvector('english', coalesce(display_name, '')), 'A') ||
                             setweight(to_tsvector('english', coalesce(tagline, '')), 'B') ||
                             setweight(to_tsvector('english', coalesce(description, '')), 'C')
                           ) stored,

  published_at             timestamptz,
  archived_at              timestamptz,
  created_by               uuid references app_user(id),
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),

  -- Honesty constraints: a status cannot exist without its supporting fact.
  check (verification_status = 'unverified' or verified_at is not null),
  check (listing_status <> 'published' or published_at is not null),
  check (listing_status <> 'archived' or archived_at is not null)
);
