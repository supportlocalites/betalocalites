-- Suggest a business (D-25, ADR-027). Anyone can suggest a business that isn't on
-- Localites. The team vets it; nothing here is ever published as typed, because a
-- phone number or email someone else gives may be personal.
create table vendor_suggestion (
  id                  uuid primary key default gen_random_uuid(),
  business_name       text not null check (char_length(btrim(business_name)) between 1 and 200),
  website             text check (char_length(website) <= 500),
  contact             text check (char_length(contact) <= 200),   -- phone or email, as typed
  category_id         uuid references category(id),               -- where the person was browsing
  search_text         text check (char_length(search_text) <= 200),
  suggested_by        uuid references app_user(id) on delete set null,  -- signed in (Stage 2+)
  visitor_id          uuid,                                       -- Localites' own cookie
  status              text not null default 'new'
                      check (status in ('new', 'added', 'declined', 'duplicate')),
  vendor_id           uuid references vendor(id),                 -- the listing it became or matches
  reviewed_by         uuid references app_user(id),
  reviewed_at         timestamptz,
  decline_reason      text,
  team_email_status   text not null default 'pending'
                      check (team_email_status in ('pending', 'sent', 'failed')),
  team_email_sent_at  timestamptz,
  team_email_error    text,
  created_at          timestamptz not null default now(),
  -- Honest records: an outcome needs its supporting facts.
  check ((status in ('added', 'duplicate')) = (vendor_id is not null)),
  check (status = 'new' or (reviewed_by is not null and reviewed_at is not null)),
  check (status <> 'declined' or decline_reason is not null),
  check ((team_email_status = 'sent') = (team_email_sent_at is not null)),
  check (team_email_status <> 'failed' or team_email_error is not null)
);
create index vendor_suggestion_open on vendor_suggestion (created_at) where status = 'new';

